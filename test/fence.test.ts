test('shu-i1b: ShukkaAccountStack creates the GitHub OIDC provider and outputs its ARN and the project names', () => {
  const stack = new ShukkaAccountStack(new App(), 'Shukka-Account', {
    projects: ['trendigle', 'orbitary'],
    env: { account: '123456789012', region: 'us-east-1' },
  });
  const t = Template.fromStack(stack);
  assert.equal(stack.stackName, 'Shukka-Account');
  t.resourceCountIs('AWS::IAM::OIDCProvider', 1);
  t.hasResource('AWS::IAM::OIDCProvider', {
    Properties: { Url: 'https://token.actions.githubusercontent.com', ClientIdList: ['sts.amazonaws.com'] },
    DeletionPolicy: 'Retain',
  });
  t.resourceCountIs('Custom::AWSCDKOpenIdConnectProvider', 0);
  const providerId = Object.keys(t.findResources('AWS::IAM::OIDCProvider'))[0];
  t.hasOutput('OidcProviderArn', { Value: { 'Fn::GetAtt': [providerId, 'Arn'] } });
  t.hasOutput('Projects', { Value: 'trendigle,orbitary' });
});

test('shu-i1b: ShukkaAccountStack can import an existing provider instead of creating one', () => {
  const arn = 'arn:aws:iam::123456789012:oidc-provider/token.actions.githubusercontent.com';
  const stack = new ShukkaAccountStack(new App(), 'Shukka-Account', { projects: [], existingOidcProviderArn: arn });
  const t = Template.fromStack(stack);
  t.resourceCountIs('AWS::IAM::OIDCProvider', 0);
  // CloudFormation refuses a template with no resources.
  assert.ok(Object.keys(t.toJSON().Resources ?? {}).length > 0);
  assert.equal(stack.oidcProviderArn, arn);
  t.hasOutput('OidcProviderArn', { Value: arn });
  t.hasOutput('Projects', { Value: 'none' });
});

