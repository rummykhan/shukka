test('shu-i1b: applyBoundary(app, project) sets the boundary on every role in an app', () => {
  const app = new App();
  const a = new Stack(app, 'Shukkatest-Box', { env: { account: '123456789012', region: 'us-east-1' } });
  const b = new Stack(app, 'Shukkatest-Ci', { env: { account: '123456789012', region: 'us-east-1' } });
  new iam.Role(a, 'InstanceRole', { assumedBy: new iam.ServicePrincipal('ec2.amazonaws.com') });
  // A role CDK makes on its own: the provider framework's Lambda role.
  const fn = new lambda.Function(b, 'Handler', {
    runtime: lambda.Runtime.NODEJS_22_X,
    handler: 'index.handler',
    code: lambda.Code.fromInline('exports.handler = async () => ({})'),
    timeout: Duration.seconds(10),
  });
  new CustomResource(b, 'Thing', { serviceToken: new cr.Provider(b, 'Provider', { onEventHandler: fn }).serviceToken });
  applyBoundary(app, 'shukkatest');
  app.synth();
  const boundary = {
    'Fn::Join': ['', ['arn:', { Ref: 'AWS::Partition' }, ':iam::', { Ref: 'AWS::AccountId' }, ':policy/shukkatest-shukka-boundary']],
  };
  let roles = 0;
  for (const stack of [a, b]) {
    const found = Template.fromStack(stack).findResources('AWS::IAM::Role');
    for (const [id, role] of Object.entries(found)) {
      roles++;
      assert.deepEqual((role.Properties as Record<string, unknown>).PermissionsBoundary, boundary, `${stack.stackName}/${id}`);
    }
  }
  assert.ok(roles >= 3, `found ${roles} roles`);
  Template.fromStack(a).hasResourceProperties('AWS::IAM::Role', { PermissionsBoundary: Match.objectLike(boundary) });
});
