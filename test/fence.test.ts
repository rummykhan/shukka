// Order-free form of a statement: scalars become sorted arrays.
const list = (v: string | string[]) => [...(Array.isArray(v) ? v : [v])].sort();
function normalise(st: PolicyStatementJson) {
  const condition: Record<string, Record<string, string[]>> = {};
  for (const [op, kv] of Object.entries(st.Condition ?? {})) {
    condition[op] = Object.fromEntries(Object.entries(kv).map(([k, v]) => [k, list(v)]));
  }
  return { Sid: st.Sid, Effect: st.Effect, Action: list(st.Action), Resource: list(st.Resource), Condition: condition };
}
const normaliseDoc = (doc: PolicyDocumentJson) => doc.Statement.map(normalise);
const docs = (f: SynthesizedFence) => [f.executionA, f.executionB, f.executionC, f.boundary];

